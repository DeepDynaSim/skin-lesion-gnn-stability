/** Build GitHub documentation with self-contained SVG mathematics.
 * Source templates retain editable LaTeX; published pages do not depend on
 * GitHub's math macro policy, Markdown escaping, webfonts, or JavaScript.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.join(repo, 'tools/math-renderer/package.json'));
const {mathjax} = require('mathjax-full/js/mathjax.js');
const {TeX} = require('mathjax-full/js/input/tex.js');
const {SVG} = require('mathjax-full/js/output/svg.js');
const {liteAdaptor} = require('mathjax-full/js/adaptors/liteAdaptor.js');
const {RegisterHTMLHandler} = require('mathjax-full/js/handlers/html.js');
const {AllPackages} = require('mathjax-full/js/input/tex/AllPackages.js');

const adaptor = liteAdaptor();
RegisterHTMLHandler(adaptor);
const input = new TeX({packages: AllPackages, formatError: (_jax, error) => {throw error;}});
const output = new SVG({fontCache: 'none'});
const document = mathjax.document('', {InputJax: input, OutputJax: output});
const assetFolder = path.join(repo, 'docs/assets/math');
const check = process.argv.includes('--check');
const files = new Map();
const records = [];
const sha = s => crypto.createHash('sha256').update(s).digest('hex');
const xml = s => s.replaceAll('&', '&amp;').replaceAll('<', '&lt;')
  .replaceAll('>', '&gt;').replaceAll('"', '&quot;');

function render(tex, display) {
  const label = tex.match(/\\tag\{([^}]+)\}/)?.[1] ?? null;
  const expression = tex.replace(/\\tag\{[^}]+\}/g, '').trim();
  const key = `${display ? 'display' : 'inline'}\n${expression}`;
  const name = `${display ? 'display' : 'inline'}-${sha(key).slice(0, 16)}.svg`;
  if (!files.has(name)) {
    const converted = document.convert(expression, {display, em: 16, ex: 8, containerWidth: 800});
    const svg = adaptor.firstChild(converted);
    const [vx, vy, vw, vh] = adaptor.getAttribute(svg, 'viewBox').split(/\s+/).map(Number);
    const font = display ? 22 : 17;
    const padding = display ? 10 : 1;
    const unitPadding = padding*1000/font;
    const width = Math.ceil(vw*font/1000+2*padding);
    const height = Math.ceil(vh*font/1000+2*padding);
    if (![vx, vy, vw, vh, width, height].every(Number.isFinite) || width < 1 || height < 1) {
      throw new Error(`Invalid SVG dimensions for ${expression}`);
    }
    if (display && width > 880) throw new Error(`Split this ${width}px equation: ${expression}`);
    adaptor.setAttribute(svg, 'width', `${width}px`);
    adaptor.setAttribute(svg, 'height', `${height}px`);
    adaptor.setAttribute(svg, 'viewBox', `${vx-unitPadding} ${vy-unitPadding} ${vw+2*unitPadding} ${vh+2*unitPadding}`);
    adaptor.removeAttribute(svg, 'style');
    adaptor.setAttribute(svg, 'role', 'img');
    const graphic = adaptor.outerHTML(svg).replaceAll('currentColor', '#111827')
      .replace('<svg ', `<svg aria-label="${xml(expression)}" `);
    const background = `<title>${xml(expression)}</title><rect x="${vx-unitPadding}" y="${vy-unitPadding}" width="${vw+2*unitPadding}" height="${vh+2*unitPadding}" fill="#ffffff"/>`;
    const result = graphic.replace(/(<svg[^>]*>)/, `$1${background}`)+'\n';
    if (/data-mjx-error|<merror|<script|<foreignObject|<text\b|href="https?:/.test(result)) {
      throw new Error(`Invalid or non-self-contained SVG: ${name}`);
    }
    files.set(name, {svg: result, width, height, expression, display});
  }
  return {name, label, ...files.get(name)};
}

for (const [template, target] of JSON.parse(fs.readFileSync(path.join(repo, 'tools/math-renderer/documents.json'), 'utf8'))) {
  const source = fs.readFileSync(path.join(repo, template), 'utf8').replaceAll('\r\n', '\n');
  const base = path.posix.relative(path.posix.dirname(target), 'docs/assets/math');
  let occurrence = 0;
  let page = source.replace(/\$\$([\s\S]*?)\$\$|\$([^$\n]+)\$/g, (_match, block, inline) => {
    const display = block !== undefined;
    const tex = (display ? block : inline).trim();
    const item = render(tex, display);
    occurrence++;
    records.push({document: target, occurrence, display, label: item.label,
      source: tex, svg: `docs/assets/math/${item.name}`, sha256: sha(item.svg)});
    const image = `<img src="${base}/${item.name}" width="${item.width}" height="${item.height}" alt="${xml(item.expression)}">`;
    return display ? `${item.label ? `**Equation (${item.label})**\n\n` : ''}<p align="center">${image}</p>` : image;
  });
  page = page.replace(/^(### \d+) (\d+)(?=\s)/gm, '$1.$2');
  const header = '<!-- Generated by scripts/render_math.mjs from '+template+'. Edit the template, then rebuild. -->\n\n';
  const notice = '> **Working manuscript template.** `[AUTHOR]`, `{{...}}`, `[TABLE:...]` and `[FIG:...]` are build markers, not completed results. The [editable LaTeX source]('+path.posix.basename(template)+') is used by the authoring scripts. The final manuscript and filled results are in the permanent archive linked from the repository README.\n\n';
  const result = header+notice+page;
  if (check) {
    if (fs.readFileSync(path.join(repo, target), 'utf8').replaceAll('\r\n', '\n') !== result) {
      throw new Error(`Stale generated page: ${target}`);
    }
  } else fs.writeFileSync(path.join(repo, target), result);
}

fs.mkdirSync(assetFolder, {recursive: true});
for (const name of fs.readdirSync(assetFolder)) {
  if (/^(display|inline)-[a-f0-9]{16}\.svg$/.test(name) && !files.has(name)) {
    if (check) throw new Error(`Obsolete generated equation: ${name}`);
    fs.unlinkSync(path.join(assetFolder, name));
  }
}
for (const [name, item] of files) {
  const file = path.join(assetFolder, name);
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== item.svg) throw new Error(`Stale equation: ${name}`);
  } else fs.writeFileSync(file, item.svg);
}
const manifest = JSON.stringify({renderer: 'MathJax 3.2.2 SVG; embedded paths, no external fonts',
  inlineFontPixels: 17, displayFontPixels: 22, expressions: records}, null, 2)+'\n';
const manifestPath = path.join(repo, 'docs/assets/math/manifest.json');
if (check) {
  if (fs.readFileSync(manifestPath, 'utf8') !== manifest) throw new Error('Stale equation manifest');
} else fs.writeFileSync(manifestPath, manifest);
console.log(`${check ? 'Verified' : 'Rendered'} ${files.size} unique SVG expressions across ${records.length} formula occurrences.`);
